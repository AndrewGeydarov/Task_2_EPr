using Npgsql;
using System;
using System.Collections.ObjectModel;
using System.Security.Cryptography;
using System.Text;
using Task_2_EPr.ViewModels;

namespace Task_2_EPr.Services;

public static class DatabaseService
{
    private static string ConnectionString
    {
        get
        {
            var fromEnvironment = Environment.GetEnvironmentVariable("TASK2EPR_POSTGRES_CONNECTION");
            if (!string.IsNullOrWhiteSpace(fromEnvironment)) return fromEnvironment;

            var settingsPath = System.IO.Path.Combine(AppContext.BaseDirectory, "appsettings.json");
            if (System.IO.File.Exists(settingsPath))
            {
                using var json = System.Text.Json.JsonDocument.Parse(System.IO.File.ReadAllText(settingsPath));
                if (json.RootElement.TryGetProperty("ConnectionStrings", out var strings) &&
                    strings.TryGetProperty("PostgreSQL", out var connection) &&
                    !string.IsNullOrWhiteSpace(connection.GetString()))
                    return connection.GetString()!;
            }

            return "Host=localhost;Port=5432;Database=task_2_epr;Username=postgres;Password=1234567890";
        }
    }

    public static void Initialize()
    {
        using var connection = new NpgsqlConnection(ConnectionString);
        connection.Open();
        using var command = connection.CreateCommand();
        command.CommandText = @"
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                login VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(64) NOT NULL,
                name VARCHAR(150) NOT NULL,
                last_name VARCHAR(150) NOT NULL
            );
            CREATE TABLE IF NOT EXISTS projects (
                id INTEGER PRIMARY KEY,
                project_name TEXT NOT NULL,
                deadline TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS team_members (
                id INTEGER PRIMARY KEY,
                last_name TEXT NOT NULL,
                name TEXT NOT NULL,
                patronymic TEXT NOT NULL,
                birth_date TEXT NOT NULL
            );";
        command.ExecuteNonQuery();

        command.CommandText = @"INSERT INTO users(login, password_hash, name, last_name)
            VALUES (@login, @hash, @name, @last_name) ON CONFLICT (login) DO NOTHING";
        command.Parameters.AddWithValue("login", "admin");
        command.Parameters.AddWithValue("hash", HashPassword("admin123"));
        command.Parameters.AddWithValue("name", "Администратор");
        command.Parameters.AddWithValue("last_name", "Системы");
        command.ExecuteNonQuery();

        InsertProject(connection, 1, "Проект медицинской клиники", "12.10.2026");
        InsertProject(connection, 2, "Проект автосервиса", "12.10.2026");
        InsertProject(connection, 3, "Просто проект", "Когда угодно");

        InsertMember(connection, 1, "Валиев", "Карим", "Динарович", "11.01.2007");
        InsertMember(connection, 2, "Волков", "Данил", "Сергеевич", "01.02.2006");
        InsertMember(connection, 3, "Чухарев", "Леонид", "Валерьевич", "25.10.2007");
    }

    private static void InsertProject(NpgsqlConnection connection, int id, string title, string deadline)
    {
        using var command = connection.CreateCommand();
        command.CommandText = @"INSERT INTO projects(id, project_name, deadline)
            VALUES (@id, @title, @deadline) ON CONFLICT (id) DO NOTHING";
        command.Parameters.AddWithValue("id", id);
        command.Parameters.AddWithValue("title", title);
        command.Parameters.AddWithValue("deadline", deadline);
        command.ExecuteNonQuery();
    }

    private static void InsertMember(NpgsqlConnection connection, int id, string lastName, string name, string patronymic, string birthDate)
    {
        using var command = connection.CreateCommand();
        command.CommandText = @"INSERT INTO team_members(id, last_name, name, patronymic, birth_date)
            VALUES (@id, @last_name, @name, @patronymic, @birth_date) ON CONFLICT (id) DO NOTHING";
        command.Parameters.AddWithValue("id", id);
        command.Parameters.AddWithValue("last_name", lastName);
        command.Parameters.AddWithValue("name", name);
        command.Parameters.AddWithValue("patronymic", patronymic);
        command.Parameters.AddWithValue("birth_date", birthDate);
        command.ExecuteNonQuery();
    }

    public static bool Authenticate(string login, string password, out string fullName)
    {
        fullName = string.Empty;
        using var connection = new NpgsqlConnection(ConnectionString);
        connection.Open();
        using var command = connection.CreateCommand();
        command.CommandText = @"SELECT name, last_name FROM users
            WHERE login = @login AND password_hash = @hash";
        command.Parameters.AddWithValue("login", login.Trim());
        command.Parameters.AddWithValue("hash", HashPassword(password));
        using var reader = command.ExecuteReader();
        if (!reader.Read()) return false;
        fullName = $"{reader.GetString(0)} {reader.GetString(1)}";
        return true;
    }

    public static ObservableCollection<Project> GetProjects()
    {
        var items = new ObservableCollection<Project>();
        using var connection = new NpgsqlConnection(ConnectionString);
        connection.Open();
        using var command = connection.CreateCommand();
        command.CommandText = "SELECT id, project_name, deadline FROM projects ORDER BY id";
        using var reader = command.ExecuteReader();
        while (reader.Read())
            items.Add(new Project { ProjectNum = reader.GetInt32(0), ProjectName = reader.GetString(1), Date = reader.GetString(2) });
        return items;
    }

    public static ObservableCollection<TeamMember> GetTeamMembers()
    {
        var items = new ObservableCollection<TeamMember>();
        using var connection = new NpgsqlConnection(ConnectionString);
        connection.Open();
        using var command = connection.CreateCommand();
        command.CommandText = "SELECT id, last_name, name, patronymic, birth_date FROM team_members ORDER BY id";
        using var reader = command.ExecuteReader();
        while (reader.Read())
            items.Add(new TeamMember { MemberNum = reader.GetInt32(0), LastName = reader.GetString(1), Name = reader.GetString(2), Patronymic = reader.GetString(3), BirthDate = reader.GetString(4) });
        return items;
    }

    private static string HashPassword(string password) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(password)));
}
